class DocumentClassifier:
    def __init__(self, document_types: list[str]):
        self.document_types = document_types

    def classify(self, text: str, official_title: str = "") -> str:
        haystack = self._normalize(f"{official_title}\n{text[:8000]}")
        rule_match = self._classify_by_rules(haystack)
        if rule_match:
            return rule_match

        best_title = ""
        best_score = 0.0

        for doc_type in self.document_types:
            candidate = self._normalize(doc_type)
            direct_score = 1.0 if candidate in haystack else 0.0
            token_score = self._token_score(candidate, haystack)
            fuzzy_score = SequenceMatcher(None, candidate, haystack[:600]).ratio()
            score = max(direct_score, token_score, fuzzy_score)
            if score > best_score:
                best_title = doc_type
                best_score = score

        return best_title if best_score >= 0.28 else "Неопределенный документ"

    def _classify_by_rules(self, haystack: str) -> str:
        for title, markers in RULES:
            if title in self.document_types and any(self._normalize(marker) in haystack for marker in markers):
                return title
        return ""

    @staticmethod
    def _normalize(value: str) -> str:
        value = value.lower().replace("ё", "е")
        value = re.sub(r"[^а-яa-z0-9]+", " ", value)
        return re.sub(r"\s+", " ", value).strip()

    @staticmethod
    def _token_score(candidate: str, haystack: str) -> float:
        tokens = [token for token in candidate.split() if len(token) > 3]
        if not tokens:
            return 0.0
        matched = sum(1 for token in tokens if token in haystack)
        return matched / len(tokens)
